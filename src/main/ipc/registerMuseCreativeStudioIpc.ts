import type { IpcMain } from 'electron'
import { museCreativeStudioService as service } from '../modules/muse-creative-studio/service'

export function registerMuseCreativeStudioIpc(ipcMain: IpcMain) {
  ipcMain.handle('plugin:museCreative:listAccounts', async () => await service.list())
  ipcMain.handle('plugin:museCreative:listAccountSummaries', async () => await service.listSummaries())
  ipcMain.handle('plugin:museCreative:createAccount', async (_e, payload) => await service.create(payload))
  ipcMain.handle('plugin:museCreative:updateAccount', async (_e, payload) => await service.update(payload))
  ipcMain.handle('plugin:museCreative:setEnabled', async (_e, payload) => await service.setEnabled(payload))
  ipcMain.handle('plugin:museCreative:acceptExit', async (_e, id: string) => await service.acceptExit(id))
  ipcMain.handle('plugin:museCreative:testAccount', async (_e, id: string) => await service.test(id))
  ipcMain.handle('plugin:museCreative:login', async (_e, id: string) => await service.login(id))
  ipcMain.handle('plugin:museCreative:cancelLogin', async (_e, id: string) => await service.cancelLogin(id))
  ipcMain.handle('plugin:museCreative:importCookies', async (_e, payload) => await service.importCookies(payload))
  ipcMain.handle('plugin:museCreative:removeAccount', async (_e, id: string) => await service.remove(id))
  ipcMain.handle('plugin:museCreative:listJobs', async () => await service.listJobs())
  ipcMain.handle('plugin:museCreative:createJobs', async (_e, payload) => await service.createJobs(payload))
  ipcMain.handle('plugin:museCreative:retryJob', async (_e, id: string) => await service.retryJob(id))
  ipcMain.handle('plugin:museCreative:dismissJob', async (_e, id: string) => await service.dismissJob(id))
  ipcMain.handle('plugin:museCreative:approveImages', async (_e, ids: string[]) => await service.approveImages(ids))
  ipcMain.handle('plugin:museCreative:redoImage', async (_e, payload) => await service.redoImage(payload))
  ipcMain.handle('plugin:museCreative:getStillCandidates', async (_e, id: string) => await service.getStillCandidates(id))
  ipcMain.handle('plugin:museCreative:pickStill', async (_e, payload) => await service.pickStill(payload))
  ipcMain.handle('plugin:museCreative:regenerateStills', async (_e, id: string) => await service.regenerateStills(id))
  ipcMain.handle('plugin:museCreative:saveSettings', async (_e, payload) => await service.saveSettings(payload))
  ipcMain.handle('plugin:museCreative:listPrompts', async (_e, kind) => await service.listPrompts(kind))
  ipcMain.handle('plugin:museCreative:updatePrompt', async (_e, payload) => await service.updatePrompt(payload))
  ipcMain.handle('plugin:museCreative:copyPrompt', async (_e, payload) => await service.copyPrompt(payload))
  ipcMain.handle('plugin:museCreative:activatePrompt', async (_e, id: string) => await service.activatePrompt(id))
  ipcMain.handle('plugin:museCreative:rollbackPrompt', async (_e, id: string) => await service.rollbackPrompt(id))
  ipcMain.handle('plugin:museCreative:moveAccount', async (_e, payload) => await service.moveAccount(payload))
  ipcMain.handle('plugin:museCreative:queryQuota', async (_e, id: string) => await service.queryQuota(id))
  ipcMain.handle('plugin:museCreative:getJob', async (_e, id: string) => await service.getJob(id))
  ipcMain.handle('plugin:museCreative:removeJobs', async (_e, ids: string[]) => await service.removeJobs(ids))
  ipcMain.handle('plugin:museCreative:addSubtitles', async (_e, payload) => await service.addSubtitles(payload))
  ipcMain.handle('plugin:museCreative:revertSubtitles', async (_e, ids: string[]) => await service.revertSubtitles(ids))
  ipcMain.handle('plugin:museCreative:exportJobs', async (_e, payload) => await service.exportJobs(payload))
  ipcMain.handle('plugin:museCreative:cancelQueuedJobs', async () => await service.cancelQueuedJobs())
  ipcMain.handle('plugin:museCreative:setQueuePaused', async (_e, paused: boolean) => await service.setQueuePaused(paused))
  ipcMain.handle('plugin:museCreative:setQueueConcurrency', async (_e, value: number) => await service.setQueueConcurrency(value))
  ipcMain.handle('plugin:museCreative:collectJob', async (_e, id: string) => await service.collectJob(id))
  ipcMain.handle('plugin:museCreative:cancelJob', async (_e, id: string) => await service.cancelJob(id))
}
